import { launch, person, settle } from './lib.mjs';
import { readFileSync } from 'node:fs';
const seed = JSON.parse(readFileSync(new URL('./out/seed.json', import.meta.url), 'utf8'));
const b = await launch(); const p = await person(b, 'http://127.0.0.1:8791', { userId: seed.users.anele.id });
await p.page.goto('/me/notifications'); await settle(p.page);
p.page.on('response', async r=>{ if(/livewire\/update/.test(r.url())) console.log('resp', r.status(), r.url(), (await r.text()).slice(0,300).replace(/\n/g,' ')); });
p.page.on('dialog', d=>{console.log('DIALOG', d.message()); d.dismiss();});
await p.context.clearCookies();
await p.page.getByRole('button', { name: 'Save notification settings' }).click();
await p.page.waitForTimeout(2500);
console.log(p.page.url());
console.log((await p.page.locator('body').innerText()).slice(0,300));
await b.close();
